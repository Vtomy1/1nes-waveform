// Step sequencer channel types and notes
export interface StepNote {
  enabled: boolean;
  midi: number; // 0 for rest
  noteName: string;
}

export interface SequencerTrack {
  channel: 'pulse1' | 'pulse2' | 'triangle' | 'noise';
  name: string;
  volume: number;
  steps: StepNote[];
}

export interface SequencerSong {
  id: string;
  title: string;
  bpm: number;
  description: string;
  tracks: SequencerTrack[];
}

